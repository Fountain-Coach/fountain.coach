const {webkit}=require('/Users/benedikteickhoff/Developer/fcis.fountain.coach/node_modules/playwright');
const assert=require('node:assert/strict'),fs=require('fs');
const base='https://192.168.8.50:8243';
(async()=>{
 const browser=await webkit.launch({headless:true});
 const results=[];
 for(const [name,width,height] of [['landscape',1180,820],['portrait',820,1180],['phone',390,844]]){
 const page=await browser.newPage({viewport:{width,height}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const response=await page.goto(base+'/estate/',{waitUntil:'domcontentloaded'});
 assert.equal(response.status(),200);
 await page.waitForFunction(()=>document.querySelector('#page-viewport')?.dataset.layout==='ready',{timeout:15000});
 await page.evaluate(()=>{window.__readerWitness='unchanged-document'});
 const first=await page.evaluate(()=>({brand:document.querySelector('.brand strong')?.textContent,volume:document.querySelector('#page-viewport').dataset.volume,books:[...document.querySelectorAll('#page-viewport .frame-book-cover [data-reader-target]')].map(x=>({name:x.innerText,target:x.dataset.readerTarget})),overflow:document.documentElement.scrollWidth>innerWidth||document.documentElement.scrollHeight>innerHeight}));
 assert.equal(first.brand,'Benedikt Eickhoff');
 assert.equal(first.volume,'library');
 assert.deepEqual(first.books.map(b=>b.target),['essays','solstice']);
 await page.screenshot({path:__dirname+'/two-books-'+name+'.png'});
 await page.locator('#page-viewport [data-reader-target="essays"]').click();
 await page.waitForFunction(()=>document.querySelector('#page-viewport')?.dataset.volume==='essays'&&document.querySelector('#page-viewport')?.dataset.layout==='ready');
 const essays=await page.evaluate(()=>[...document.querySelectorAll('#source-flow .frame-toc-item [data-reader-target]')].map(x=>x.dataset.readerTarget));
 assert.equal(essays.length,7);
 assert.equal(essays[0],'essay--reframe-and-the-business-value-of-the-estate');
 assert.equal(essays.at(-1),'essay--the-door-is-a-score');
 await page.getByRole('button',{name:'Return to Bookshelf inside the reader'}).click();
 await page.waitForFunction(()=>document.querySelector('#page-viewport')?.dataset.volume==='library'&&document.querySelector('#page-viewport')?.dataset.layout==='ready');
 await page.locator('#page-viewport [data-reader-target="solstice"]').click();
 await page.waitForFunction(()=>document.querySelector('#page-viewport')?.dataset.volume==='solstice'&&document.querySelector('#page-viewport')?.dataset.layout==='ready');
 assert.equal(await page.locator('#page-viewport [data-reader-target="solstice-reading-01"]').count(),1);
 await page.locator('#page-viewport [data-reader-target="solstice-reading-01"]').click();
 await page.waitForFunction(()=>document.querySelector('#page-viewport')?.dataset.volume==='solstice-reading-01'&&document.querySelector('#page-viewport')?.dataset.layout==='ready');
 const toc=await page.evaluate(()=>[...document.querySelectorAll('#source-flow .frame-toc-item a')].map(x=>({name:x.innerText,target:x.dataset.readerTarget})));
 assert.equal(toc.length,32);
 assert.equal(toc.filter(x=>x.target.includes('2026')||x.target.includes('2025')).length,30);
 const firstWork=toc.find(x=>x.target.endsWith('2025-12-22-anweisung-an-den-schmerz'));
 assert.ok(firstWork);
 await page.getByLabel('Choose publication').selectOption(firstWork.target);
 await page.waitForFunction(v=>document.querySelector('#page-viewport')?.dataset.volume===v&&document.querySelector('#page-viewport')?.dataset.layout==='ready',firstWork.target,{timeout:17000});
 const work=await page.evaluate(()=>({loaded:[...document.querySelectorAll('#page-viewport img')].every(i=>i.naturalWidth>0),originalImage:document.querySelector('#source-flow img')?.getAttribute('src'),title:document.querySelector('#source-flow h2')?.textContent,body:document.querySelector('#source-flow').innerText.slice(0,160),page:document.querySelector('#page-count')?.textContent,witness:window.__readerWitness}));
 assert.equal(work.title,'Anweisung an den Schmerz');
 assert.ok(work.originalImage?.startsWith('/solstice/assets/edition/'));
 assert.equal(work.witness,'unchanged-document');
 await page.screenshot({path:__dirname+'/two-books-first-reading-work-'+name+'.png'});
 results.push({name,first,essays,tocLength:toc.length,firstWork:work,errors});
 console.log('PASS',name,JSON.stringify({first,essayCount:essays.length,solsticeToc:toc.length,work,errors}));
 assert.equal(errors.length,0);
 await page.close();
 }
 await browser.close();
 fs.writeFileSync(__dirname+'/two-books-browser-evidence.json',JSON.stringify({origin:base,results,failures:0},null,2)+'\n');
})().catch(e=>{console.error('FAILED',e.stack);process.exitCode=2});
